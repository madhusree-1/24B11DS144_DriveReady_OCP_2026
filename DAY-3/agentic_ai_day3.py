# Initialize the LLM
llm = ChatGroq(
    model="openai/gpt-oss-120b",
    temperature=0
)

from langchain_core.prompts import ChatPromptTemplate, MessagesPlaceholder
from langchain_core.output_parsers import StrOutputParser

SYSTEM = SYSTEM = """ROLE: You are the friendly assistant for Sweet Crumbs Home Bakery.

FACTS:
- Plum cake: Rs 500.
- Chocolate cake: Rs 650.
- Cupcake: Rs 80 each.
- Orders require at least 24 hours' notice.
- All cakes have eggless versions.

RULES:
- Always mention the correct price.
- Calculate totals accurately.
- For multiple items, calculate the total correctly.
- Clearly mention that all cakes are available in eggless versions when asked.
- If an order is requested with less than 24 hours' notice, explain the 24-hour notice requirement.
- If asked about delivery locations, delivery schedules or unavailable information, say "I'll check with the owner."
- Never guarantee a delivery time or place.
- Never invent business information.

FORMAT:
- Friendly and concise.
- Under 50 words.
- Respond in English or Telugu, matching the customer.
"""

prompt = ChatPromptTemplate.from_messages([
    ("system", SYSTEM),
    MessagesPlaceholder("history"),          # the chat so far goes here
    ("human", "{question}"),
])

chain = prompt | llm | StrOutputParser()

history = []

def ask(question: str) -> str:
    answer = chain.invoke({"history": history, "question": question})
    history.extend([("human", question), ("ai", answer)])
    return answer

print(ask("Hi, I'm Madhu. Do you make eggless cakes?"))
print(ask("What's my name?"))

history

import csv

def run_tests(path: str = "/test.csv") -> None:
    rows = list(csv.DictReader(open(path)))
    passed = 0
    for row in rows:
        answer = chain.invoke({"history": [], "question": row["question"]})
        ok = row["must_include"].lower() in answer.lower()
        passed += ok
        print("PASS" if ok else "FAIL", "|", row["question"], "→", answer[:70])
    print(f"\n{passed}/{len(rows)} passed ({passed / len(rows):.0%})")

run_tests()