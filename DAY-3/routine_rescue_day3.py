import os
from google.colab import userdata
from langchain_groq import ChatGroq

os.environ["GROQ_API_KEY"] = userdata.get("Grok_API")

llm = ChatGroq(
    model="openai/gpt-oss-120b",
    temperature=0
)

print("Routine Rescue AI — Day 3 connection ready!")

from langchain_core.prompts import ChatPromptTemplate, MessagesPlaceholder
from langchain_core.output_parsers import StrOutputParser

SYSTEM = """
ROLE:
You are Routine Rescue AI, a friendly productivity assistant
for students.

PURPOSE:
Help students organize tasks, identify priorities, and create
realistic daily schedules based on their available time.

RULES:
- Prioritize tasks based on deadlines, importance and available time.
- Do not invent deadlines or task details.
- If essential details are missing, ask the user.
- Make realistic plans with breaks when appropriate.
- If the user has unfinished tasks, help reorganize them.
- Do not shame the user for unfinished tasks.
- Never pretend that tasks have been saved permanently.
- Respond in English or Telugu/Tenglish matching the user.

FORMAT:
- Friendly and practical.
- Use clear schedules or bullet points when helpful.
- Avoid unnecessary lengthy explanations.
"""

prompt = ChatPromptTemplate.from_messages([
    ("system", SYSTEM),
    MessagesPlaceholder("history"),
    ("human", "{question}")
])

chain = prompt | llm | StrOutputParser()

print("Routine Rescue AI chain created!")

history = []

def ask(question: str) -> str:

    answer = chain.invoke({
        "history": history,
        "question": question
    })

    history.extend([
        ("human", question),
        ("ai", answer)
    ])

    return answer

print(ask("Hi, I'm Madhu. I have 2 DSA problems today."))

print(ask("I also have a Python assignment due tomorrow."))

print(ask("What tasks did I tell you about?"))

