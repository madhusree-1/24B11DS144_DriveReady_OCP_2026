from typing import Literal
from pydantic import BaseModel, Field
from langchain.tools import tool

PRIORITIES = {
    "high": 3,
    "medium": 2,
    "low": 1
}

TASK_CATEGORIES = [
    "DSA",
    "College",
    "Python",
    "Project",
    "Other"
]

class Task(BaseModel):
    """A student's task stored in the task tracker."""

    task: str = Field(description="Task description")

    subject: str = Field(
        description="Task category or subject"
    )

    priority: Literal[
        "high", "medium", "low"
    ] = Field(description="Task priority")

    deadline: str = Field(
        description="Deadline provided by the student"
    )

    estimated_minutes: int = Field(
        description="Estimated task duration in minutes",
        ge=1
    )

    status: Literal[
        "pending", "completed"
    ] = Field(default="pending")

@tool
def estimate_task_time(
    task: str,
    difficulty: Literal["easy", "medium", "hard"] = "medium"
) -> str:
    """Estimate approximate minutes needed for a student task."""

    estimates = {
        "easy": 25,
        "medium": 45,
        "hard": 90
    }

    minutes = estimates[difficulty]

    return (
        f"Estimated time for '{task}': "
        f"{minutes} minutes ({difficulty} difficulty). "
        "This is an approximate estimate."
    )

AVAILABLE_MINUTES = 120

@tool
def get_available_time() -> str:
    """Get the student's currently available study time."""

    return (
        f"The student has {AVAILABLE_MINUTES} "
        "minutes available today."
    )

@tool
def add_task(
    task: str,
    subject: str,
    priority: Literal["high", "medium", "low"],
    deadline: str,
    estimated_minutes: int
) -> str:
    """Save a student task to the Task Tracker sheet.

    Use only after the student confirms saving the task.
    """

    try:
        new_task = Task(
            task=task,
            subject=subject,
            priority=priority,
            deadline=deadline,
            estimated_minutes=estimated_minutes,
            status="pending"
        )

    except Exception as e:
        return f"Task validation failed: {e}"

    ws.append_row([
        new_task.task,
        new_task.subject,
        new_task.priority,
        new_task.deadline,
        new_task.estimated_minutes,
        new_task.status
    ])

    return (
        f"Saved task: {new_task.task} | "
        f"Priority: {new_task.priority} | "
        f"Estimated time: {new_task.estimated_minutes} minutes"
    )

@tool
def view_tasks() -> str:
    """View tasks already saved in the Google Sheets tracker."""

    records = ws.get_all_records()

    if not records:
        return "No tasks have been saved yet."

    return str(records)

SYSTEM = """ROLE:
You are Routine Rescue AI, a friendly student productivity assistant.

GOALS:
1. Help students organize tasks.
2. Prioritize tasks based on deadline and importance.
3. Create realistic study plans.
4. Estimate task durations using the estimation tool.
5. Check available study time using the available time tool.
6. Save tasks to Google Sheets using the add_task tool.
7. Retrieve saved tasks using the view_tasks tool.

RULES:
- Never invent deadlines given by the student.
- Use tools whenever their functionality is required.
- If task duration is unknown, use estimate_task_time.
- Before saving a task, collect task, subject, priority,
  deadline and estimated time.
- Ask for explicit confirmation before saving tasks.
- Never call add_task before confirmation.
- If details are missing, ask the student.
- Do not claim a task was saved unless the tool succeeded.
- Make plans realistic and include short breaks.
- Match the student's language: English or Tenglish.

FORMAT:
Keep responses clear, friendly and practical.
"""

from langchain.agents import create_agent

tools = [
    estimate_task_time,
    get_available_time,
    add_task,
    view_tasks
]

agent = create_agent(
    model=llm,
    tools=tools,
    system_prompt=SYSTEM
)

print("Routine Rescue AI agent created!")

history = []

def chat(text: str) -> str:
    global history

    try:
        result = agent.invoke({
            "messages": history + [
                {"role": "user", "content": text}
            ]
        })

        history = result["messages"]

        return history[-1].content

    except Exception as e:
        print("Agent error:", e)

        return (
            "Sorry, I encountered an error. "
            "Please try again."
        )

